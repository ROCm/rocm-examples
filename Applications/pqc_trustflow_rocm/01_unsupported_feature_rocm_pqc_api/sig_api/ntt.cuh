/* ================================================================
 *  NTT 函数 (两种算法共用同一份代码)
 * ================================================================ */

/*
 * ntt(a): 就地前向 NTT 变换
 *   使用有符号 Montgomery 蝶形: t = mont_reduce(zeta * a[j+len])
 *                              a[j+len] = a[j] - t
 *                              a[j]     = a[j] + t
 */
static __device__ __noinline__ void ntt(int32_t a[PARAM_N]) {
    unsigned int len, start, j, k;
    int32_t zeta, t;

    k = 0;
    for (len = 128; len > 0; len >>= 1) {
        for (start = 0; start < PARAM_N; start = j + len) {
            zeta = ntt_zetas[++k];
            for (j = start; j < start + len; ++j) {
                t = montgomery_reduce((int64_t)zeta * a[j + len]);
                a[j + len] = a[j] - t;
                a[j]       = a[j] + t;
            }
        }
    }
}

/*
 * invntt_tomont(a): 就地逆 NTT 变换
 *
 * ML-DSA: 逆蝶形使用 -ntt_zetas[--k], 全部 N 系数乘以 INTT_F
 * Aigis:  逆蝶形使用独立的 ntt_zetas_inv[k++], 仅前 N/2 系数归一化
 *         (Aigis 的 zetas_inv 不等于 -zetas 的逆序, 必须用独立表)
 */
static __device__ __noinline__ void invntt_tomont(int32_t a[PARAM_N]) {
    unsigned int start, len, j, k;
    int32_t t, zeta;
    const int32_t f = INTT_F;

#if ALGORITHM == ALGO_MLDSA
    k = PARAM_N;
    for (len = 1; len < PARAM_N; len <<= 1) {
        for (start = 0; start < PARAM_N; start = j + len) {
            zeta = -ntt_zetas[--k];
            for (j = start; j < start + len; ++j) {
                t          = a[j];
                a[j]       = t + a[j + len];
                a[j + len] = t - a[j + len];
                a[j + len] = montgomery_reduce((int64_t)zeta * a[j + len]);
            }
        }
    }
    for (j = 0; j < PARAM_N; ++j)
        a[j] = montgomery_reduce((int64_t)f * a[j]);

#elif ALGORITHM == ALGO_AIGIS
    k = 0;
    for (len = 1; len < PARAM_N; len <<= 1) {
        for (start = 0; start < PARAM_N; start = j + len) {
            zeta = ntt_zetas_inv[k++];
            for (j = start; j < start + len; ++j) {
                t          = a[j];
                a[j]       = t + a[j + len];
                a[j + len] = t - a[j + len];
                a[j + len] = montgomery_reduce((int64_t)zeta * a[j + len]);
            }
        }
    }
    for (j = 0; j < PARAM_N / 2; ++j)
        a[j] = montgomery_reduce((int64_t)f * a[j]);
#endif
}

